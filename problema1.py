import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt
from tensorflow.keras import layers

# --- Definición de la Capa ---
class GrayscaleLayer(layers.Layer):
    def __init__(self, **kwargs):
        super(GrayscaleLayer, self).__init__(**kwargs)

    def call(self, inputs):
        # inputs shape: (batch, alto, ancho, 3)
        r, g, b = inputs[:, :, :, 0], inputs[:, :, :, 1], inputs[:, :, :, 2]

        # Fórmula estándar de conversión a escala de grises
        grayscale = 0.299 * r + 0.587 * g + 0.114 * b

        # Mantiene la consistencia devolviendo la forma (batch, alto, ancho, 1)
        return tf.expand_dims(grayscale, axis=-1)

# --- Ejemplo de Uso con una Imagen de tu PC ---
if __name__ == "__main__":
    # Reemplaza esta ruta con la ubicación real de tu imagen (ej. 'C:/Users/TuUsuario/Imágenes/foto.jpg' o 'foto.png')
    ruta_imagen = '/content/1.png'

    try:
        # 1. Cargar la imagen desde el disco (respeta el alto y ancho originales de tu imagen)
        imagen_cargada = tf.keras.utils.load_img(ruta_imagen)

        # 2. Convertir la imagen a un arreglo de NumPy
        imagen_array = tf.keras.utils.img_to_array(imagen_cargada)

        # 3. Añadir la dimensión de lote (batch) para que la forma sea (1, alto, ancho, 3)
        imagen_original = tf.expand_dims(imagen_array, axis=0)

        # 4. Instanciar la capa personalizada
        capa_grises = GrayscaleLayer()

        # 5. Aplicar la capa a tu imagen
        imagen_gris = capa_grises(imagen_original)

        # 6. Mostrar dimensiones resultantes
        print("Forma de la imagen original:", imagen_original.shape)
        print("Forma de la imagen en escala de grises:", imagen_gris.shape)

        # 7. Visualizar los resultados con Matplotlib
        plt.figure(figsize=(10, 5))

        plt.subplot(1, 2, 1)
        plt.title("Imagen Original (RGB)")
        plt.imshow(imagen_original[0].numpy().astype("uint8"))
        plt.axis("off")

        plt.subplot(1, 2, 2)
        plt.title("Imagen en Escala de Grises")
        # Se elimina el último canal [:, :, 0] para mostrar una imagen 2D en escala de grises
        plt.imshow(imagen_gris[0, :, :, 0].numpy(), cmap='gray')
        plt.axis("off")

        plt.show()

    except FileNotFoundError:
        print(f"Error: No se encontró el archivo en la ruta '{ruta_imagen}'. Por favor, verifica que la ruta y el nombre sean correctos.")