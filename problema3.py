# --- Ejercicio 3 ---

import numpy as np
import tensorflow as tf
from tensorflow.keras import layers, Sequential
import matplotlib.pyplot as plt

class Poly3Layer(layers.Layer):
    def __init__(self, **kwargs):
        super(Poly3Layer, self).__init__(**kwargs)

    def build(self, input_shape):
        # Creamos 4 pesos entrenables: a0, a1, a2, a3
        self.a = self.add_weight(shape=(4,),
                                 initializer='random_normal',
                                 trainable=True,
                                 name='coeficientes')
        super(Poly3Layer, self).build(input_shape)

    def call(self, inputs):
        # inputs es x. Calculamos el polinomio
        # a[0] + a[1]*x + a[2]*x^2 + a[3]*x^3
        x = inputs
        return self.a[0] + self.a[1]*x + self.a[2]*(x**2) + self.a[3]*(x**3)

# Datos para entrenar contra cos(2x)
x_train = np.linspace(-1, 1, 500).reshape(-1, 1).astype(np.float32)
y_target = np.cos(2 * x_train)

# Modelo usando SOLO la capa personalizada
model_poly = Sequential([
    Poly3Layer(input_shape=(1,))
])

model_poly.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.1), loss='mse')

print("Entrenando capa polinómica...")
history = model_poly.fit(x_train, y_target, epochs=500, verbose=0)

# Obtener coeficientes finales
coeffs = model_poly.layers[0].get_weights()[0]
print(f"Coeficientes aprendidos [a0, a1, a2, a3]: {coeffs}")

# Graficar
y_pred_poly = model_poly.predict(x_train)
plt.figure()
plt.plot(x_train, y_target, label='cos(2x) Real')
plt.plot(x_train, y_pred_poly, '--', label='Polinomio Grado 3')
plt.title('Ajuste Polinomio Grado 3 a cos(2x)')
plt.legend()
plt.show()