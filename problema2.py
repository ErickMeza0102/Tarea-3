import numpy as np
import matplotlib.pyplot as plt
from tensorflow.keras import Sequential
from tensorflow.keras.layers import Dense

# --- Ejercicio 2 ---

def entrenar_funcion(func, nombre_func, epochs=2000):
    # 1. Generar datos
    x = np.linspace(-1, 1, 1000).reshape(-1, 1).astype(np.float32)
    y = func(x)

    # 2. Crear Red
    model = Sequential([
        Dense(64, activation='tanh', input_shape=(1,)),
        Dense(64, activation='tanh'),
        Dense(1) # Salida lineal
    ])

    model.compile(optimizer='adam', loss='mse')

    # 3. Entrenar
    print(f"Entrenando {nombre_func}...")
    model.fit(x, y, epochs=epochs, verbose=0)

    # 4. Graficar
    y_pred = model.predict(x)

    plt.figure()
    plt.plot(x, y, label='Analítica', linewidth=2)
    plt.plot(x, y_pred, '--', label='Red Neuronal', linewidth=2)
    plt.title(f'Aproximación: {nombre_func}')
    plt.legend()
    plt.show()

# (a) f(x) = 3*sin(pi*x)
entrenar_funcion(lambda x: 3 * np.sin(np.pi * x), "3sin(πx)")

# (b) f(x) = 1 + 2x + 4x^3
entrenar_funcion(lambda x: 1 + 2*x + 4*(x**3), "1 + 2x + 4x^3")