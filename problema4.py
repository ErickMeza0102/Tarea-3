import numpy as np
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense
import matplotlib.pyplot as plt

# --- Ejercicio 4 (a) ---

# Dominio [-5, 5]
x_dom = np.linspace(-5, 5, 1000).reshape(-1, 1).astype(np.float32)
# Puntos de colocación (donde evaluamos la física)
x_train_colloc = tf.convert_to_tensor(x_dom, dtype=tf.float32)
# Punto inicial
x_initial = tf.convert_to_tensor([[0.0]], dtype=tf.float32)
y_initial = tf.convert_to_tensor([[0.0]], dtype=tf.float32)

# Red Neuronal
model_ode_a = Sequential([
    Dense(64, activation='tanh', input_shape=(1,)),
    Dense(64, activation='tanh'),
    Dense(1)
])

optimizer = tf.keras.optimizers.Adam(learning_rate=0.001)

@tf.function
def train_step_ode_a():
    with tf.GradientTape() as tape:
        # 1. Predicción en puntos de física
        with tf.GradientTape() as tape2:
            tape2.watch(x_train_colloc)
            y_pred = model_ode_a(x_train_colloc)

        # Derivada dy/dx
        dy_dx = tape2.gradient(y_pred, x_train_colloc)

        # Ecuación: x*y' + y - x^2*cos(x) = 0
        # Nota: En x=0 la ecuación tiene una singularidad, pero el residuo se calcula automáticamente
        equation_residual = x_train_colloc * dy_dx + y_pred - (x_train_colloc**2 * tf.cos(x_train_colloc))
        loss_physics = tf.reduce_mean(tf.square(equation_residual))

        # 2. Condición Inicial (Pérdida de datos)
        y_pred_init = model_ode_a(x_initial)
        loss_initial = tf.reduce_mean(tf.square(y_pred_init - y_initial))

        # Pérdida total
        total_loss = loss_physics + 100 * loss_initial # Ponderamos más la inicial para asegurar convergencia

    grads = tape.gradient(total_loss, model_ode_a.trainable_variables)
    optimizer.apply_gradients(zip(grads, model_ode_a.trainable_variables))
    return total_loss

# Entrenamiento
epochs = 3000
print("Entrenando ODE (a)...")
for i in range(epochs):
    loss = train_step_ode_a()
    if i % 500 == 0:
        print(f"Epoch {i}, Loss: {loss.numpy()}")

# Solución Analítica (Calculada manualmente o con sympy)
# y = x * sin(x) + cos(x) - 1 ... (verificando con condiciones iniciales)
def sol_analitica_a(x):
    return x * np.sin(x) + np.cos(x) - 1

y_pred_a = model_ode_a.predict(x_dom)
plt.figure()
plt.plot(x_dom, sol_analitica_a(x_dom), label='Analítica')
plt.plot(x_dom, y_pred_a, '--', label='PINN')
plt.title('ODE (a): xy\' + y = x^2 cos(x)')
plt.legend()
plt.show()

# --- Ejercicio 4 (b) ---

x_dom_b = np.linspace(-5, 5, 1000).reshape(-1, 1).astype(np.float32)
x_train_b = tf.convert_to_tensor(x_dom_b, dtype=tf.float32)

# Condiciones iniciales
t0 = tf.convert_to_tensor([[0.0]], dtype=tf.float32)
y0 = tf.convert_to_tensor([[1.0]], dtype=tf.float32)   # y(0)
dy0 = tf.convert_to_tensor([[-0.5]], dtype=tf.float32) # y'(0)

model_ode_b = Sequential([
    tf.keras.layers.Input(shape=(1,)),
    Dense(64, activation='tanh'),
    Dense(64, activation='tanh'),
    Dense(1)
])
optimizer_b = tf.keras.optimizers.Adam(learning_rate=0.001)

@tf.function
def train_step_ode_b():
    with tf.GradientTape() as tape:
        # Para la segunda derivada anidamos correctamente las dos cintas
        with tf.GradientTape() as tape2:
            tape2.watch(x_train_b)
            with tf.GradientTape() as tape3:
                tape3.watch(x_train_b)
                y_pred = model_ode_b(x_train_b)

            dy_dx = tape3.gradient(y_pred, x_train_b)

        d2y_dx2 = tape2.gradient(dy_dx, x_train_b)

        # Ecuación: y'' + y = 0
        equation_residual = d2y_dx2 + y_pred
        loss_physics = tf.reduce_mean(tf.square(equation_residual))

        # Condiciones iniciales
        with tf.GradientTape() as tape_init:
            tape_init.watch(t0)
            y_pred_0 = model_ode_b(t0)

        dy_pred_0 = tape_init.gradient(y_pred_0, t0)

        loss_init_val = tf.reduce_mean(tf.square(y_pred_0 - y0))
        loss_init_der = tf.reduce_mean(tf.square(dy_pred_0 - dy0))

        total_loss = loss_physics + 100 * (loss_init_val + loss_init_der)

    grads = tape.gradient(total_loss, model_ode_b.trainable_variables)
    optimizer_b.apply_gradients(zip(grads, model_ode_b.trainable_variables))
    return total_loss

# Entrenamiento
print("Entrenando ODE (b)...")
for i in range(3000):
    loss = train_step_ode_b()
    if i % 500 == 0:
        print(f"Epoch {i}, Loss: {loss.numpy()}")

# Solución Analítica: y = A*cos(x) + B*sin(x)
# y(0)=1 -> A=1
# y'(0)=-0.5 -> B=-0.5
# y = cos(x) - 0.5*sin(x)
def sol_analitica_b(x):
    return np.cos(x) - 0.5 * np.sin(x)

y_pred_b = model_ode_b.predict(x_dom_b)
plt.figure()
plt.plot(x_dom_b, sol_analitica_b(x_dom_b), label='Analítica')
plt.plot(x_dom_b, y_pred_b, '--', label='PINN')
plt.title('ODE (b): y\'\' = -y')
plt.legend()
plt.show()